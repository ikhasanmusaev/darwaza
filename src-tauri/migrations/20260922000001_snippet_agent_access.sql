-- Сниппет доступен агенту (#220).
--
-- ВЫКЛЮЧЕНО по умолчанию и для новых, и для существующих сниппетов — по той
-- же причине, что и доступ к хосту (#201): после обновления приложения агент
-- не должен внезапно получить то, о чём человека не спрашивали.
--
-- Отдельный флаг на каждый сниппет, а не общее разрешение, нужен здесь
-- сильнее, чем где-либо ещё. В сниппеты пишут команды целиком, как их
-- набирают руками, — вместе с паролями, токенами и ключами прямо в строке.
-- Общее «агент видит сниппеты» означало бы отдать ему их все, включая те,
-- о содержимом которых владелец давно забыл.
--
-- Колонка НЕ синхронизируется: список колонок для обмена задан в коде явно и
-- эту не включает. Решение «пускать ли агента» принимается на устройстве, как
-- и для хостов, — чужой ноутбук не должен получать его вместе с сниппетом.
ALTER TABLE snippets ADD COLUMN agent_access BOOLEAN NOT NULL DEFAULT 0;

-- Выборка «какие сниппеты доступны агенту» идёт на каждый его запрос списка.
CREATE INDEX IF NOT EXISTS snippets_agent_access ON snippets (agent_access) WHERE agent_access = 1;
