-- Доступ агента к хосту (#201).
--
-- ВЫКЛЮЧЕНО по умолчанию и для новых, и для существующих хостов. Это не
-- перестраховка: включённый по умолчанию доступ означал бы, что после
-- обновления приложения агент внезапно получил власть над всеми боевыми
-- серверами пользователя, а тот об этом не просил и не узнал.
--
-- Флаг именно на хосте, а не общий: разрешить агенту тестовый стенд и не
-- разрешить продакшн — обычное и разумное желание.
ALTER TABLE hosts ADD COLUMN agent_access BOOLEAN NOT NULL DEFAULT 0;

-- Выборка «какие хосты доступны агенту» идёт на каждый его запрос.
CREATE INDEX IF NOT EXISTS hosts_agent_access ON hosts (agent_access) WHERE agent_access = 1;
