-- Читающие команды с sudo, разрешённые агенту на этом хосте (#214).
--
-- Зачем колонка, а не общая настройка: список зависит от сервера. На одном
-- нужен `ufw status`, на другом `nft list ruleset`, на третьем не нужно
-- ничего. Общий список означал бы, что разрешение, данное ради одного
-- сервера, действует на всех.
--
-- NULL и пустая строка — ничего не разрешено. Это и есть значение по
-- умолчанию: доступ агента сам по себе выключен, а sudo внутри него —
-- отдельное решение владельца, принимаемое для каждого сервера.
--
-- Почему нельзя просто внести `sudo` в список читающих команд: `sudo` не
-- программа, а приставка к любой другой. «Разрешить sudo» означало бы
-- «разрешить всё с правами root» — то есть отменить саму модель, где
-- изменения подтверждает человек.
ALTER TABLE hosts ADD COLUMN agent_sudo_read TEXT;
