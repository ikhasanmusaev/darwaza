-- Журнал действий агента (#204).
--
-- Нужен не для отладки, а для доверия: человек, открывший агенту боевой
-- сервер, должен иметь возможность посмотреть, что тот делал. Без такой
-- возможности «разрешить доступ» — прыжок в темноту.
--
-- Пишется ВСЁ, включая отказы: попытка выполнить запрещённое интереснее
-- успешного `ls`, а именно она и пропала бы, если писать только удачное.
CREATE TABLE IF NOT EXISTS agent_log (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Имя хоста строкой, а не ссылкой: запись должна пережить удаление
    -- хоста. Журнал, теряющий строки при уборке, бесполезен как журнал.
    host        TEXT,
    action      TEXT    NOT NULL,   -- run | read | list
    detail      TEXT,               -- команда или путь
    -- Итог: ok | refused | failed. Отказы хранятся наравне с успехами.
    outcome     TEXT    NOT NULL,
    -- Код возврата команды, если она выполнялась.
    exit_code   INTEGER,
    -- Причина отказа или текст ошибки.
    note        TEXT
);

-- Просмотр всегда идёт от свежего к старому.
CREATE INDEX IF NOT EXISTS agent_log_at ON agent_log (at DESC);
