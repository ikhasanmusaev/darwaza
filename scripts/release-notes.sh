#!/usr/bin/env bash
# Собирает описание релиза из CHANGELOG.md (английский, основной),
# CHANGELOG_ru.md и CHANGELOG_uz.md: сначала английский текст версии, затем
# «## Русский» и «## O‘zbekcha». Он же становится описанием релиза на GitHub и
# GitLab.
#
# Описание не пишется заново при выпуске: написанное дважды расходится, и
# расходится незаметно. Единственный источник — три файла журнала.
#
# Нет раздела версии хотя бы в одном из трёх — ошибка выпуска: релиз, у
# которого на одном из языков описания нет, лучше не выпускать совсем.
#
# Использование: scripts/release-notes.sh 0.1.1   (или v0.1.1)
set -euo pipefail

cd "$(dirname "$0")/.."

[ $# -ge 1 ] || { echo "нужна версия: $0 0.1.1" >&2; exit 2; }
version=${1#v}

# Раздел одной версии из одного файла.
section() {
  awk -v v="$version" '
    # Начало нужного раздела.
    $0 ~ "^## \\[" v "\\] — " { inside = 1; next }
    # Любой следующий заголовок того же уровня закрывает раздел.
    inside && /^## / { exit }
    # Хвост файла — ссылки и примечания — в описание релиза не попадает.
    inside && (/^<!--/ || /^\[/) { exit }
    inside { print }
  ' "$1"
}

# То же с обрезкой пустых краёв и схлопыванием пустых строк подряд.
tidy() {
  sed -e '/./,$!d' | awk 'BEGIN{blank=0} {if ($0=="") {blank++} else {blank=0}; if (blank<2) print}'
}

# Пустой раздел — это ошибка выпуска, а не мелочь оформления: релиз без
# описания заставляет читать историю коммитов, чего мы от людей не ждём.
load() {
  local file=$1 text
  [ -f "$file" ] || { echo "ОШИБКА: нет файла $file" >&2; exit 1; }
  text=$(section "$file")
  if [ -z "$(printf '%s' "$text" | tr -d '[:space:]')" ]; then
    echo "ОШИБКА: в $file нет непустого раздела для версии $version" >&2
    exit 1
  fi
  printf '%s\n' "$text" | tidy
}

# Сначала читаем все три: пропущенный язык должен остановить сборку до того,
# как в вывод попадёт хоть строка.
en=$(load CHANGELOG.md)
ru=$(load CHANGELOG_ru.md)
uz=$(load CHANGELOG_uz.md)

printf '%s\n\n---\n\n## Русский\n\n%s\n\n---\n\n## O‘zbekcha\n\n%s\n' "$en" "$ru" "$uz"
