#!/usr/bin/env bash
# Достаёт из CHANGELOG.md раздел одной версии — он же становится описанием
# релиза в GitLab.
#
# Описание не пишется заново при выпуске: написанное дважды расходится, и
# расходится незаметно. Единственный источник — CHANGELOG.md.
#
# Использование: scripts/release-notes.sh 0.1.0   (или v0.1.0)
set -euo pipefail

cd "$(dirname "$0")/.."

[ $# -ge 1 ] || { echo "нужна версия: $0 0.1.0" >&2; exit 2; }
version=${1#v}

notes=$(awk -v v="$version" '
  # Начало нужного раздела.
  $0 ~ "^## \\[" v "\\] — " { inside = 1; next }
  # Любой следующий заголовок того же уровня закрывает раздел.
  inside && /^## / { exit }
  # Хвост файла — ссылки и примечания — в описание релиза не попадает.
  inside && (/^<!--/ || /^\[/) { exit }
  inside { print }
' CHANGELOG.md)

# Пустой раздел — это ошибка выпуска, а не мелочь оформления: релиз без
# описания заставляет читать историю коммитов, чего мы от людей не ждём.
if [ -z "$(printf '%s' "$notes" | tr -d '[:space:]')" ]; then
  echo "ОШИБКА: в CHANGELOG.md нет непустого раздела для версии $version" >&2
  exit 1
fi

printf '%s\n' "$notes" | sed -e '/./,$!d' | awk 'BEGIN{blank=0} {if ($0=="") {blank++} else {blank=0}; if (blank<2) print}'
